/**
 * Generates src/flags.ts: team name -> flag-icons code.
 *
 *     node scripts/build-flags.mjs
 *
 * Committed output, so the app pays no runtime cost and ships none of
 * flag-icons' country.json. Re-run when dataset/countries_names.csv changes.
 *
 * Teams with no flag in the package -- Zanzibar, Tibet, Kurdistan, the
 * historical sides -- are left out on purpose; the UI falls back to the team's
 * colour swatch for anything missing here.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const at = (p) => fileURLToPath(new URL(p, import.meta.url))

/** Names this dataset spells differently from flag-icons. */
const ALIAS = {
  Bonaire: 'bq', // bq is "Bonaire, Sint Eustatius and Saba"; Sint Eustatius plays
  // as its own side here, so it keeps the colour fallback rather than
  // showing a flag identical to Bonaire's.
  'British Virgin Islands': 'vg',
  Brunei: 'bn',
  'Cape Verde': 'cv',
  Congo: 'cg',
  Czechia: 'cz',
  'DR Congo': 'cd',
  'East Timor': 'tl',
  'FS Micronesia': 'fm',
  'Ivory Coast': 'ci',
  Macao: 'mo',
  Palestine: 'ps',
  'St Vincent & Grenadines': 'vc',
  Tahiti: 'pf', // Tahiti competes under French Polynesia
  Turkey: 'tr', // flag-icons lists it as Türkiye
  'United States': 'us',
  'US Virgin Islands': 'vi',
}

const norm = (s) =>
  s
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '')

const countries = JSON.parse(readFileSync(at('../node_modules/flag-icons/country.json'), 'utf8'))
const codes = new Set(countries.map((c) => c.code))
const byName = new Map(countries.map((c) => [norm(c.name), c.code]))

for (const [team, code] of Object.entries(ALIAS)) {
  if (!codes.has(code)) throw new Error(`alias ${team} -> ${code}: no such flag`)
}

const rows = readFileSync(at('../../dataset/countries_names.csv'), 'utf8').trim().split('\n').slice(1)
const teams = new Set()
for (const row of rows) {
  const cols = row.split(',')
  if (cols.length !== 3) throw new Error(`expected 3 columns, got ${cols.length}: ${row}`)
  teams.add(cols[1].trim())
}

const flags = {}
const missing = []
for (const team of [...teams].sort()) {
  const code = ALIAS[team] ?? byName.get(norm(team))
  if (code) flags[team] = code
  else missing.push(team)
}

const body = Object.entries(flags)
  .map(([team, code]) => `  ${JSON.stringify(team)}: '${code}',`)
  .join('\n')

writeFileSync(
  at('../src/flags.ts'),
  `/**
 * Team name -> flag-icons country code. GENERATED by scripts/build-flags.mjs,
 * do not edit by hand.
 *
 * ${missing.length} of ${teams.size} teams have no flag in the package and are absent here:
 * ${missing.join(', ')}.
 * Those fall back to the team's colour swatch.
 */
export const FLAGS: Record<string, string> = {
${body}
}
`,
)

console.log(`${Object.keys(flags).length} of ${teams.size} teams mapped`)
console.log(`no flag available (falls back to colour): ${missing.join(', ')}`)
